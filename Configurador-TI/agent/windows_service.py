"""Native SCM adapter with LocalService identity. No auto elevation.

Installation requires an explicit administrator terminal and an immutable EXE
under Program Files. Agent identity is generated by LocalService, using its own
CurrentUser DPAPI context. A one-use enrollment bootstrap is machine-DPAPI
protected AND ACL-restricted; it is removed as soon as enrollment succeeds.
"""
